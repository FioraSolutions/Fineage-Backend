#!/usr/bin/env python3
"""Transcribe the Mobius CT 0 Interlude manor data into data/manor.json and add the manor items to data/items.json.

Reads the Mobius datapack (not copied into this repo) and writes original JSON (no GPL source copied).

Mobius reference (L2J_Mobius_CT_0_Interlude/dist/game/data):
  Seeds.xml              <castle id><crop id seedId mature_Id reward1 reward2 alternative level limit_seed limit_crops/>
  stats/npcs/*.xml       <status canBeSown="true"> (monsters that take a seed), <param name="manor_id"> on the
                         Manor Manager merchants (the castle whose seeds they sell)
  stats/items/*.xml      seed / crop / mature crop / reward EtcItem templates (name, icon, price, weight)

Seeds whose item template is missing from the CT 0 item data (Mobius ships a few level-82 rows) are skipped:
nobody can own them, so the castle could never sell them.

Usage:
  python3 tools/import_manor.py /path/to/mobius/dist/game/data [out=data/manor.json]
  (a flat folder with Seeds.xml, npcs/*.xml and items/*.xml works too)
"""

from __future__ import annotations

import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def find_dir(base: Path, *names: str) -> Path:
    for name in names:
        p = base / name
        if p.is_dir():
            return p
    raise SystemExit(f"missing {names} under {base}")


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    base = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "data/manor.json"
    npc_dir = find_dir(base, "stats/npcs", "npcs")
    item_dir = find_dir(base, "stats/items", "items")

    templates: dict[int, dict] = {}
    for f in sorted(item_dir.glob("*.xml")):
        for e in ET.parse(f).getroot().iter("item"):
            sets = {s.get("name"): s.get("val") for s in e.findall("set")}
            templates[int(e.get("id"))] = {"type": e.get("type"), "name": e.get("name"), **sets}

    seeds = []
    skipped = []
    for castle in ET.parse(base / "Seeds.xml").getroot().iter("castle"):
        castle_id = int(castle.get("id"))
        for c in castle.iter("crop"):
            seed_id = int(c.get("seedId"))
            if seed_id not in templates:
                skipped.append(seed_id)
                continue
            seeds.append({
                "seedId": seed_id,
                "cropId": int(c.get("id")),
                "matureId": int(c.get("mature_Id")),
                "reward1": int(c.get("reward1")),
                "reward2": int(c.get("reward2")),
                "castleId": castle_id,
                "alternative": c.get("alternative") == "true",
                "level": int(c.get("level")),
                "limitSeed": int(c.get("limit_seed")),
                "limitCrop": int(c.get("limit_crops")),
                "seedPrice": int(templates[seed_id].get("price", 1)),
                "cropPrice": int(templates.get(int(c.get("id")), {}).get("price", 1)),
            })

    sowable = []
    managers = []
    for f in sorted(npc_dir.glob("*.xml")):
        for npc in ET.parse(f).getroot().iter("npc"):
            npc_id = int(npc.get("id"))
            status = npc.find("status")
            if status is not None and status.get("canBeSown") == "true":
                sowable.append(npc_id)
            params = npc.find("parameters")
            if params is not None and npc.get("name") == "Manor Manager":
                for p in params.iter("param"):
                    if p.get("name") == "manor_id":
                        managers.append({"npcId": npc_id, "castleId": int(p.get("value"))})

    doc = {
        "reference": "L2J Mobius CT0 Interlude data/Seeds.xml (seed -> crop per castle manor), stats/npcs canBeSown and "
                     "Manor Manager manor_id, item reference prices from stats/items. Generated by tools/import_manor.py.",
        "seeds": sorted(seeds, key=lambda s: (s["castleId"], s["level"], s["alternative"], s["seedId"])),
        "managers": sorted(managers, key=lambda m: m["npcId"]),
        "sowableNpcIds": sorted(set(sowable)),
    }
    out.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")

    # Seed / crop / mature crop / reward items missing from data/items.json (etc rows, existing rows untouched).
    items_path = ROOT / "data/items.json"
    items = json.loads(items_path.read_text())
    have = {i["id"] for i in items["items"]}
    want = set()
    for s in seeds:
        want |= {s["seedId"], s["cropId"], s["matureId"], s["reward1"], s["reward2"]}
    added = 0
    for iid in sorted(want - have):
        t = templates.get(iid)
        if t is None or t["type"] != "EtcItem" or not t.get("icon"):
            continue
        row = {"id": iid, "name": t["name"], "kind": "etc"}
        if t.get("is_stackable") == "true":
            row["stackable"] = True
        row["icon"] = t["icon"]
        row["price"] = int(t.get("price", 0))
        row["weight"] = int(t.get("weight", 0))
        items["items"].append(row)
        added += 1
    items["items"].sort(key=lambda i: i["id"])
    items_path.write_text(json.dumps(items, indent=2, ensure_ascii=False) + "\n")
    print(f"seeds={len(seeds)} skipped={sorted(set(skipped))} managers={len(managers)} sowable={len(set(sowable))} items+={added}")


if __name__ == "__main__":
    main()
