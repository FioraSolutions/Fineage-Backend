#!/usr/bin/env python3
"""Compare Fineage.Net.Contract with the Unity client's in-assets copy.

The client repo is the source of the comparison tool (`scripts/sync-net-contract.py`),
including Unity C# 9 lowering. This wrapper runs that script against this backend
tree and checks the result against docs/data/net-contract-client-gap.txt.

The gap file is the explicit pending/incompatibility list. CI fails when the live
comparison disagrees with it (drift grew, shrank, or a previously matching file
changed). An empty gap file is the accepted end state: the two copies match.

  python3 scripts/check-net-contract-sync.py --backend . --client /path/to/Fineage
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFAULT_GAP = REPO / "docs" / "data" / "net-contract-client-gap.txt"


def parse_gap(path: Path) -> list[str]:
    lines: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        lines.append(line)
    return lines


def parse_client_report(text: str) -> list[str]:
    paths: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("- ") and stripped.endswith(".cs"):
            paths.append(stripped[2:].strip())
    return paths


def run_client_check(client_repo: Path, backend_contract: Path) -> tuple[int, str]:
    script = client_repo / "scripts" / "sync-net-contract.py"
    if not script.is_file():
        raise SystemExit(f"error: client sync script not found: {script}")
    proc = subprocess.run(
        [
            sys.executable,
            str(script),
            "--check",
            "--backend",
            str(backend_contract),
            "--ref",
            "",
        ],
        cwd=str(client_repo),
        capture_output=True,
        text=True,
    )
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend", default=str(REPO), help="Fineage-Backend repo root")
    parser.add_argument("--client", required=True, help="Fineage (Unity client) repo root")
    parser.add_argument(
        "--gap",
        default=str(DEFAULT_GAP),
        help="recorded pending-sync path list (default: docs/data/net-contract-client-gap.txt)",
    )
    parser.add_argument(
        "--write-gap",
        action="store_true",
        help="rewrite the gap file from the live comparison",
    )
    args = parser.parse_args()

    backend = Path(args.backend).resolve()
    client = Path(args.client).resolve()
    gap_path = Path(args.gap).resolve()
    contract = backend / "src" / "Fineage.Net.Contract"
    if not contract.is_dir():
        print(f"error: backend contract not found: {contract}", file=sys.stderr)
        return 2

    rc, report = run_client_check(client, contract)
    live = parse_client_report(report)

    # The client script exits 0 only when there is no drift. If it exits 0, live must be empty.
    if rc not in (0, 1):
        print(report, file=sys.stderr)
        print(f"error: sync-net-contract.py exited {rc}", file=sys.stderr)
        return 2

    if rc == 0 and live:
        print(report, file=sys.stderr)
        print("error: client script exited 0 but listed drift paths", file=sys.stderr)
        return 2
    if rc == 1 and not live:
        print(report, file=sys.stderr)
        print("error: client script exited 1 but no .cs drift paths were parsed", file=sys.stderr)
        return 2

    live_sorted = sorted(live)

    if args.write_gap:
        gap_path.parent.mkdir(parents=True, exist_ok=True)
        body = "\n".join(
            [
                "# Pending Unity-client sync for Fineage.Net.Contract.",
                "# Each path is relative to src/Fineage.Net.Contract and is missing on the",
                "# client or differs after the client's Unity C# 9 lowering.",
                "# Regenerated by scripts/check-net-contract-sync.py --write-gap.",
                "# An empty list (only these comments) means the copies match.",
                "",
                *live_sorted,
                "",
            ]
        )
        gap_path.write_text(body, encoding="utf-8")
        print(f"wrote {gap_path} ({len(live_sorted)} pending paths)")
        return 0

    if not gap_path.is_file():
        print(f"error: gap file not found: {gap_path}", file=sys.stderr)
        return 1

    recorded = parse_gap(gap_path)
    recorded_sorted = sorted(recorded)
    if recorded != recorded_sorted or len(recorded) != len(set(recorded)):
        print("error: gap file must be unique paths in sorted order", file=sys.stderr)
        return 1

    if live_sorted != recorded_sorted:
        live_set, rec_set = set(live_sorted), set(recorded_sorted)
        grew = sorted(live_set - rec_set)
        shrank = sorted(rec_set - live_set)
        print("Net contract client sync does not match docs/data/net-contract-client-gap.txt", file=sys.stderr)
        if grew:
            print("  new / unrecorded drift:", file=sys.stderr)
            for p in grew:
                print(f"    + {p}", file=sys.stderr)
        if shrank:
            print("  recorded but no longer drifting (remove from the gap file):", file=sys.stderr)
            for p in shrank:
                print(f"    - {p}", file=sys.stderr)
        print(
            "\nUpdate the gap file (explicit pending client sync) or sync the Unity client.",
            file=sys.stderr,
        )
        print("Live client report:\n" + report, file=sys.stderr)
        return 1

    if live_sorted:
        print(
            f"Net contract client sync matches the recorded pending list "
            f"({len(live_sorted)} files). Client still needs a sync PR."
        )
        for p in live_sorted:
            print(f"  - {p}")
    else:
        print("Net contract client sync is clean: no pending files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
