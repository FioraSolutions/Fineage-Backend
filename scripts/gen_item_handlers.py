"""Generate data/item-handlers.json from Mobius CT0 Interlude item XMLs.

Extracts item id → handler for Book, Maps, RollingDice, Calculator, SpecialXMas.
Also copies data/html/help from the Mobius tree when --copy-help is set.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
from collections import defaultdict
from pathlib import Path

WANT = {"Book", "Maps", "RollingDice", "Calculator", "SpecialXMas"}
HANDLER_RE = re.compile(r'<set\s+name="handler"\s+val="([^"]+)"\s*/>', re.I)
ITEM_RE = re.compile(r'<item\s+id="(\d+)"[\s\S]*?</item>')


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--mobius",
        type=Path,
        default=Path("ref/mobius-ct0-interlude"),
        help="Mobius CT0 Interlude checkout",
    )
    ap.add_argument("--out", type=Path, default=Path("data/item-handlers.json"))
    ap.add_argument("--copy-help", action="store_true")
    args = ap.parse_args()

    items_dir = args.mobius / "dist/game/data/stats/items"
    by_handler: dict[str, list[int]] = defaultdict(list)
    items: dict[str, str] = {}
    for path in sorted(items_dir.glob("*.xml")):
        text = path.read_text(errors="ignore")
        for m in ITEM_RE.finditer(text):
            iid = int(m.group(1))
            hm = HANDLER_RE.search(m.group(0))
            if hm and hm.group(1) in WANT:
                h = hm.group(1)
                by_handler[h].append(iid)
                items[str(iid)] = h

    payload = {
        "reference": (
            "L2J Mobius CT0 Interlude stats/items handler="
            "Book|Maps|RollingDice|Calculator|SpecialXMas. "
            "Generated by scripts/gen_item_handlers.py."
        ),
        "handlers": {h: ids for h, ids in sorted(by_handler.items())},
        "items": dict(sorted(items.items(), key=lambda kv: int(kv[0]))),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {args.out} ({len(items)} items)")

    if args.copy_help:
        src = args.mobius / "dist/game/data/html/help"
        dst = Path("data/html/help")
        dst.mkdir(parents=True, exist_ok=True)
        n = 0
        for p in src.rglob("*"):
            if p.is_file():
                target = dst / p.relative_to(src)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(p, target)
                n += 1
        print(f"copied {n} help html files to {dst}")


if __name__ == "__main__":
    main()
