#!/usr/bin/env python3
"""Convert Mobius CT_0_Interlude <dropLists> (stats/npcs/*.xml) into our data/drops/npc-<id>-<slug>.json.
Every NPC id in data/spawns/*.json is converted. Hand-written files (no "generated": true) are kept.
<drop><group chance> -> death.groups (weighted pick inside group, as Mobius); loose <drop><item> -> its own
group (group chance = item chance); <spoil><item> -> corpse.items.
Usage: gen_drops.py [mobius npcs xml dir] (default ref/mobius-ct0-interlude/data/stats/npcs)"""
import json, re, sys, pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "ref/mobius-ct0-interlude/dist/game/data/stats/npcs"
if not src.is_dir():
    src = ROOT / "ref/mobius-ct0-interlude/data/stats/npcs"
out = ROOT / "data/drops"

ids = set()
for spawn in (ROOT / "data/spawns").glob("*.json"):
    ids |= {int(x) for x in re.findall(r'"npcId"\s*:\s*(\d+)', spawn.read_text())}

hand = set()
for p in out.glob("*.json"):
    d = json.loads(p.read_text())
    if d.get("generated"):
        p.unlink()
    else:
        hand.add(d["npcId"])

def num(v):
    f = float(v)
    return int(f) if f.is_integer() else f

def item(e, chance=None):
    mn, mx = int(e.get("min", 1)), int(e.get("max", 1))
    if mn <= 0 or mx <= 0:
        return None
    return {"itemId": int(e.get("id")), "min": mn, "max": mx,
            "chance": num(chance if chance is not None else e.get("chance", 100))}

written = []
for f in sorted(src.glob("*.xml")):
    for npc in ET.parse(f).getroot().iter("npc"):
        nid = int(npc.get("id"))
        if nid not in ids or nid in hand:
            continue
        dl = npc.find("dropLists")
        if dl is None:
            continue
        groups = []
        drop = dl.find("drop")
        if drop is not None:
            for ch in drop:
                if ch.tag == "group":
                    items = [i for i in (item(x) for x in ch.findall("item")) if i]
                    if items:
                        groups.append({"chance": num(ch.get("chance", 100)), "items": items})
                elif ch.tag == "item":
                    i = item(ch, 100)
                    if i:
                        groups.append({"chance": num(ch.get("chance", 100)), "items": [i]})
        if not groups:
            continue
        doc = {"generated": True,
               "reference": f"Generated by scripts/gen_drops.py from Mobius CT_0_Interlude stats/npcs/{f.name}. Do not edit by hand; drop 'generated' to take ownership.",
               "npcId": nid, "name": npc.get("name", ""), "level": int(npc.get("level", 0)),
               "death": {"groups": groups}}
        spoil = dl.find("spoil")
        if spoil is not None:
            si = [i for i in (item(x) for x in spoil.findall("item")) if i]
            if si:
                doc["corpse"] = {"items": si}
        slug = re.sub(r"[^a-z0-9]+", "-", doc["name"].lower()).strip("-") or "npc"
        (out / f"npc-{nid}-{slug}.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
        written.append((nid, doc["name"]))

print(f"spawned ids={len(ids)} hand={sorted(hand)} written={len(written)}")
for nid, n in written:
    print(nid, n)
