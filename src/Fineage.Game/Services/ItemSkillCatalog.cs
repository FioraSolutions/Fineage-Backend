using System.Text.Json;

namespace Fineage.Game.Services;

/// <summary>One executable effect of an <c>ItemSkills</c> item (Mobius <c>item_skill</c> chain).</summary>
public sealed record ItemSkillEffect
{
    public string Kind { get; init; } = "";

    /// <summary>Mobius skill id. Chosen so <c>data/skill-stat-effects.json</c> carries the buff funcs.</summary>
    public int SkillId { get; init; }

    public int SkillLevel { get; init; } = 1;

    public string Name { get; init; } = "";

    public int AbnormalLevel { get; init; } = 1;

    public int DurationSeconds { get; init; }

    /// <summary>Heal / mana / HoT power. Percent kinds read it as a percentage of the maximum.</summary>
    public int Power { get; init; }

    public int Ticks { get; init; } = 1;

    public int X { get; init; }

    public int Y { get; init; }

    public int Z { get; init; }

    /// <summary>DispelBySlot slot name (POISON, BLEEDING, …).</summary>
    public string Slot { get; init; } = "";

    public int Count { get; init; } = 1;

    /// <summary>Restoration grant.</summary>
    public int ItemId { get; init; }
}

/// <summary>One usable item: what Mobius destroys a stack of and what it casts.</summary>
public sealed record ItemSkillUse(int ItemId, string Name, int ReuseDelayMs, IReadOnlyList<ItemSkillEffect> Effects);

/// <summary>
/// Mobius <c>handler="ItemSkills"</c> items (<c>data/item-skills.json</c>, generated by
/// <c>scripts/gen_item_skills.py</c>): potions, scrolls of escape, recovery scrolls, compressed shot packages.
/// <para>
/// Mobius <c>UseItem</c> sends a non-equippable item to its <c>ItemHandler</c>, which casts the item skills and destroys
/// one item when the cast lands. The zone executes the flattened effect list instead of a skill engine.
/// </para>
/// </summary>
public sealed class ItemSkillCatalog
{
    public const string FileName = "item-skills.json";

    static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true
    };

    readonly Dictionary<int, ItemSkillUse> _byItem;

    ItemSkillCatalog(Dictionary<int, ItemSkillUse> byItem) => _byItem = byItem;

    public static ItemSkillCatalog Empty { get; } = new([]);

    public int Count => _byItem.Count;

    public bool TryGet(int itemId, out ItemSkillUse use) => _byItem.TryGetValue(itemId, out use!);

    public static ItemSkillCatalog LoadDefault()
    {
        var path = TeleportCatalog.FindFile(FileName);
        return path == null ? Empty : Parse(File.ReadAllText(path), path);
    }

    public static ItemSkillCatalog Parse(string json, string source = FileName)
    {
        FileDto? file;
        try
        {
            file = JsonSerializer.Deserialize<FileDto>(json, JsonOptions);
        }
        catch (JsonException ex)
        {
            throw new InvalidDataException($"{source} is not an item skill table.", ex);
        }

        var byItem = new Dictionary<int, ItemSkillUse>();
        foreach (var row in file?.Items ?? [])
        {
            if (row.ItemId <= 0)
                throw new InvalidDataException($"{source} has an item row without a valid id.");
            var effects = (row.Effects ?? []).Where(e => !string.IsNullOrWhiteSpace(e.Kind)).ToArray();
            if (effects.Length == 0)
                continue;
            byItem[row.ItemId] = new ItemSkillUse(row.ItemId, row.Name ?? "", Math.Max(0, row.ReuseDelayMs), effects);
        }

        return new ItemSkillCatalog(byItem);
    }

    sealed class FileDto
    {
        public List<RowDto>? Items { get; set; }
    }

    sealed class RowDto
    {
        public int ItemId { get; set; }
        public string? Name { get; set; }
        public int ReuseDelayMs { get; set; }
        public List<ItemSkillEffect>? Effects { get; set; }
    }
}
